// Embeds assets/docker/* into src/core/assets.generated.ts so that the extension
// bundle and the standalone MCP server do not depend on files at runtime.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'docker');
const files = readdirSync(dir).filter(f => !f.startsWith('.')).sort();

const entries = files.map(f => [f, readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n')]);
const hash = createHash('sha256');
for (const [name, content] of entries) {
    hash.update(name).update('\0').update(content).update('\0');
}

const out = `// AUTO-GENERATED by scripts/generate-assets.mjs – do not edit.
/* eslint-disable */
export const DOCKER_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(entries), null, 4)};

/** Hash of all docker assets – part of the shared web image tag. */
export const DOCKER_ASSETS_HASH = ${JSON.stringify(hash.digest('hex').slice(0, 10))};
`;
const target = join(root, 'src', 'core', 'assets.generated.ts');
let current = '';
try {
    current = readFileSync(target, 'utf8');
} catch {
    // first run
}
if (current !== out) {
    writeFileSync(target, out);
    console.log(`generated ${target} (${files.length} files)`);
}
