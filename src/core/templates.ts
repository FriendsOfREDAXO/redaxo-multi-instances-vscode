/** Files of the build context (instance `docker/` directory) that define the web image. */
export const IMAGE_FILES = ['Dockerfile', 'entrypoint.sh', 'php.ini', 'vhost.conf'] as const;

const q = (value: string | number | boolean): string => JSON.stringify(String(value));

export function hashImageFiles(files: Readonly<Record<string, string>>): string {
    const hash = createHash('sha256');
    for (const name of [...IMAGE_FILES].sort()) {
        hash.update(name).update('\0').update((files[name] ?? '').replace(/\r\n/g, '\n')).update('\0');
    }
    return hash.digest('hex').slice(0, 10);
}

/** Shared image name: identical for all instances with the same PHP version and build files. */
export function webImageName(phpImageTag: string, filesHash: string): string {
    return `redaxo-mi-web:${phpImageTag.replace(/-apache$/, '')}-${filesHash}`;
}

export function defaultImageFiles(): Record<string, string> {
    const files: Record<string, string> = {};
    for (const name of IMAGE_FILES) {
        files[name] = DOCKER_ASSETS[name];
    }
    return files;
}

export interface ComposeContext {
    settings: Pick<CoreSettings, 'lang' | 'timezone'>;
    ports: SharedPorts;
    /** Hash of the instance build files (see {@link hashImageFiles}). */
    filesHash: string;
    /** Host user id (Linux) so that files created in the container belong to the user. */
    hostUid?: number;
    hostGid?: number;
}

/** docker-compose.yml for a v2 (or modernized) instance. */
export function renderCompose(cfg: InstanceConfig, ctx: ComposeContext): string {
    const l = cfg.layout;
    const primaryHost = instanceHosts(cfg.name, cfg.domains)[0];
    const server = `${proxyUrl(ctx.ports, primaryHost)}/`;

    const env: Array<[string, string | number | boolean]> = [
        ['APACHE_DOCUMENT_ROOT', l.docroot],
        ['XDEBUG_ENABLED', cfg.xdebug ? '1' : '0'],
        ['MAIL_HOST', 'redaxo-mi-mailpit'],
        ['MAIL_FROM', `noreply@${primaryHost}`],
    ];
    if (ctx.hostUid !== undefined && ctx.hostUid > 0) {
        env.push(['HOST_UID', ctx.hostUid], ['HOST_GID', ctx.hostGid ?? ctx.hostUid]);
    }
    if (cfg.kind === 'redaxo' && cfg.redaxo6) {
        const enc = encodeURIComponent;
        env.push(
            ['REDAXO6_SOURCE', cfg.redaxo6],
            ['REDAXO6_BRANCH', '6.x'],
            ['REDAXO_LANG', ctx.settings.lang],
            ['REDAXO_ADMIN_USER', cfg.admin?.user ?? 'admin'],
            ['REDAXO_ADMIN_PASSWORD', cfg.admin?.password ?? ''],
            ['REX_MODE', 'dev'],
            ['REX_INSTANCE_NAME', cfg.name],
            ['REX_BASE_URL', server],
            ['DATABASE_URL', `mysql://${enc(cfg.db.user)}:${enc(cfg.db.password)}@${l.dbService}:3306/${enc(cfg.db.name)}`],
            ['MAILER_DSN', 'smtp://redaxo-mi-mailpit:1025'],
            ['REX_MAILER_FROM', `noreply@${primaryHost}`],
        );
    } else if (cfg.kind === 'redaxo') {
        env.push(
            ['REDAXO_AUTO_INSTALL', '1'],
            ['REDAXO_VERSION', cfg.redaxoVersion ?? 'latest'],
            ['REDAXO_SERVER', server],
            ['REDAXO_SERVERNAME', cfg.name],
            ['REDAXO_ERROR_EMAIL', `admin@${primaryHost}`],
            ['REDAXO_LANG', ctx.settings.lang],
            ['REDAXO_TIMEZONE', ctx.settings.timezone],
            ['REDAXO_DB_HOST', l.dbService],
            ['REDAXO_DB_NAME', cfg.db.name],
            ['REDAXO_DB_LOGIN', cfg.db.user],
            ['REDAXO_DB_PASSWORD', cfg.db.password],
            ['REDAXO_ADMIN_USER', cfg.admin?.user ?? 'admin'],
            ['REDAXO_ADMIN_PASSWORD', cfg.admin?.password ?? ''],
        );
    }

    const dbVolume = l.dbStorage.type === 'bind' ? `${l.dbStorage.path}:/var/lib/mysql` : `${l.dbStorage.volume}:/var/lib/mysql`;
    const volumes = [`  ${COMPOSER_CACHE_VOLUME}:\n    external: true`];
    if (l.dbStorage.type === 'volume') {
        volumes.push(l.dbStorage.external
            ? `  ${l.dbStorage.volume}:\n    external: true\n    name: ${l.dbStorage.external}`
            : `  ${l.dbStorage.volume}:`);
    }
    const volumesSection = `\nvolumes:\n${volumes.join('\n')}\n`;

    return `# Generated by the REDAXO Multi-Instances VS Code extension – changes will be overwritten.
# Put your own additions into docker-compose.override.yml (merged automatically by Docker Compose).
name: ${l.composeProject}

services:
  ${l.webService}:
    image: ${webImageName(cfg.phpImageTag, ctx.filesHash)}
    build:
      context: ./docker
      args:
        PHP_IMAGE_TAG: ${q(cfg.phpImageTag)}
    container_name: ${l.webContainer}
    restart: unless-stopped
    ports:
      - "127.0.0.1:${cfg.ports.http}:80"
    environment:
${env.map(([k, v]) => `      ${k}: ${q(v)}`).join('\n')}
    volumes:
      - ./${l.webroot}:/var/www/html
      - ./docker/custom-setup.sh:/usr/local/bin/custom-setup.sh:ro
      - ${COMPOSER_CACHE_VOLUME}:/var/cache/composer
    extra_hosts:
      - "host.docker.internal:host-gateway"
    depends_on:
      ${l.dbService}:
        condition: service_healthy
    networks:
      - default
      - ${SHARED_NETWORK}

  ${l.dbService}:
    image: mariadb:${cfg.mariadb}
    container_name: ${l.dbContainer}
    restart: unless-stopped
    command:
      - --character-set-server=utf8mb4
      - --collation-server=utf8mb4_unicode_ci
      - --max-allowed-packet=256M
    environment:
      MARIADB_ROOT_PASSWORD: ${q(cfg.db.rootPassword)}
      MARIADB_DATABASE: ${q(cfg.db.name)}
      MARIADB_USER: ${q(cfg.db.user)}
      MARIADB_PASSWORD: ${q(cfg.db.password)}
      MARIADB_AUTO_UPGRADE: "1"
    ports:
      - "127.0.0.1:${cfg.ports.db}:3306"
    volumes:
      - ${dbVolume}
      - ./docker/initdb:/docker-entrypoint-initdb.d:ro
    healthcheck:
      test: ["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]
      interval: 5s
      timeout: 5s
      retries: 60
      start_period: 30s
    networks:
${l.dbAliases?.length ? `      default:\n        aliases:\n${l.dbAliases.map(a => `          - ${a}`).join('\n')}\n      ${SHARED_NETWORK}: {}` : `      - default\n      - ${SHARED_NETWORK}`}
${volumesSection}
networks:
  ${SHARED_NETWORK}:
    external: true
`;
}

